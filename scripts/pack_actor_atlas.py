"""Build a capped lossless atlas derivative with source-space frame coordinates.

This is build packaging, not artwork generation. Originals remain in art-source.
Run from repository root with Pillow/WebP installed.
"""
from pathlib import Path
import json
from PIL import Image

actor = 'vending-golem'
padding = 2
poses = ['attack', 'hit', 'defeat', 'guard']
images = [(pose, Image.open(f'art-source/battle/actors/{actor}-{pose}-v1.png').convert('RGBA')) for pose in poses]
cell_width = max(im.width for _, im in images) + padding * 2
cell_height = max(im.height for _, im in images) + padding * 2
width = cell_width * 2
height = cell_height * 2
if max(width, height) > 4096:
    raise ValueError('Atlas exceeds 4096 texture limit')
atlas = Image.new('RGBA', (width, height))
frames = {}
for index, (pose, im) in enumerate(images):
    x = (index % 2) * cell_width + padding
    y = (index // 2) * cell_height + padding
    atlas.paste(im, (x, y))
    # Extrusion uses exact edge pixels, with no interpolation or source alteration.
    for d in range(1, padding + 1):
        atlas.paste(im.crop((0, 0, 1, im.height)), (x-d, y))
        atlas.paste(im.crop((im.width-1, 0, im.width, im.height)), (x+im.width-1+d, y))
        atlas.paste(im.crop((0, 0, im.width, 1)), (x, y-d))
        atlas.paste(im.crop((0, im.height-1, im.width, im.height)), (x, y+im.height-1+d))
    for dx in range(padding):
        for dy in range(padding):
            for px, sx in [(x-padding+dx, 0), (x+im.width+dx, im.width-1)]:
                for py, sy in [(y-padding+dy, 0), (y+im.height+dy, im.height-1)]:
                    atlas.putpixel((px, py), im.getpixel((sx, sy)))
    frames[pose] = dict(rect=[x,y,im.width,im.height],sourceSize=[im.width,im.height],offset=[0,0],footAnchor=[.5,.94])

out = Path(f'public/assets/battle/actors/{actor}-poses-v1.webp')

for pose, im in images:
    x,y,w,h = frames[pose]['rect']
    assert atlas.crop((x,y,x+w,y+h)).tobytes() == im.tobytes(), f'{pose} source pixels changed'
resolution = 1
while max(width, height) * resolution > 2048:
    resolution /= 2
runtime = atlas.resize((int(width * resolution), int(height * resolution)), Image.Resampling.LANCZOS)
runtime.save(out, 'WEBP', lossless=True, exact=True, method=6)
assert Image.open(out).convert('RGBA').tobytes() == runtime.tobytes(), 'Derivative round trip changed pixels'
source = dict(width=width, height=height, runtimeWidth=runtime.width, runtimeHeight=runtime.height, resolution=resolution)
data = 'import { AtlasFrame } from "../core/battleVisualModels";\n'
data += '// Generated by scripts/pack_actor_atlas.py; do not edit frame coordinates.\n'
data += 'export const GOLEM_ATLAS_FRAMES: Record<string,AtlasFrame> = '+json.dumps(frames,indent=2)+';\n'
data += 'export const GOLEM_ATLAS_SOURCE = '+json.dumps({'/assets/battle/actors/'+out.name:source},indent=2)+';\n'
Path('src/data/actorAtlasFrames.ts').write_text(data)
print(f'Verified {len(frames)} frames: {runtime.width}x{runtime.height} runtime ({width}x{height} logical), {out.stat().st_size:,} encoded bytes, {runtime.width*runtime.height*4:,} decoded RGBA bytes')
